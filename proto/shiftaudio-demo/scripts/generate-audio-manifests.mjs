import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const audioRoot = path.resolve(__dirname, '../public/audio')
const safetyRoot = path.resolve(__dirname, '../public/messages/safety')
const safetyOut = path.resolve(__dirname, '../src/config/safetyManifest.ts')

async function listDirs(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true })
  return entries.filter((e) => e.isDirectory()).map((e) => e.name)
}

async function listTracks(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true })
  return entries
    .filter((e) => e.isFile() && e.name.toLowerCase().endsWith('.mp3'))
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b))
}

async function writeManifest(folder) {
  const folderPath = path.join(audioRoot, folder)
  const tracks = await listTracks(folderPath)
  const manifest = { tracks }
  const manifestPath = path.join(folderPath, 'manifest.json')
  await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8')
}

function titleFromFile(name) {
  const base = name.replace(/\.[^/.]+$/, '')
  return base
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase())
}

async function writeSafetyManifest() {
  const entries = await fs.readdir(safetyRoot, { withFileTypes: true })
  const files = entries
    .filter((e) => e.isFile() && e.name.toLowerCase().endsWith('.wav'))
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b))

  const items = files.map((file) => ({ file, label: titleFromFile(file) }))
  const content =
    `// This file is auto-generated by scripts/generate-audio-manifests.mjs\n` +
    `export const safetyManifest = ${JSON.stringify(items, null, 2)} as const;\n`
  await fs.writeFile(safetyOut, content, 'utf8')
}

async function main() {
  try {
    const folders = await listDirs(audioRoot)
    if (!folders.length) {
      console.warn('[audio-manifest] No audio folders found at', audioRoot)
      return
    }

    await Promise.all(folders.map((f) => writeManifest(f)))
    await writeSafetyManifest()
    console.log(`[audio-manifest] Wrote manifests for: ${folders.join(', ')}`)
  } catch (err) {
    console.error('[audio-manifest] Failed to generate manifests:', err)
    process.exitCode = 1
  }
}

void main()
